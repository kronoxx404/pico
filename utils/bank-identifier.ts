/**
 * Identifica el nombre del banco colombiano asociado a un BIN.
 * Se recomienda pasar solo los primeros 6 dígitos de la tarjeta.
 * @param binString - El BIN como string.
 * @returns El nombre del banco o "Sin información de bin".
 */
export function identifyBankByBin(binString: string | null): string {
  if (!binString) {
    return "Sin información de bin";
  }

  // Tomamos solo los primeros 6 dígitos y aseguramos que sea un número entero
  const bin = parseInt(binString.substring(0, 6));

  if (isNaN(bin)) {
    return "BIN inválido";
  }

  // Lógica de identificación basada en el código PHP original
  if (BANCOLOMBIA_BINS.has(bin)) {
    return "Bancolombia";
  } else if (DAVIVIENDA_BINS.has(bin)) {
    return "Davivienda";
  } else if (BOGOTA_BINS.has(bin)) {
    return "Bogota";
  } else if (COLPATRIA_BINS.has(bin)) {
    return "Colpatria";
  } else if (BBVA_BINS.has(bin)) {
    return "BBVA";
  } else if (OCCIDENTE_BINS.has(bin)) {
    return "Occidente";
  } else if (TUYA_BINS.has(bin)) {
    return "Tuya";
  } else if (FALABELLA_BINS.has(bin)) {
    return "Falabella";
  } else if (AVVILLAS_BINS.has(bin)) {
    return "AV Villas";
  } else if (SERFINANZA_BINS.has(bin)) {
    return "Serfinanza";
  } else if (FINANDINA_BINS.has(bin)) {
    return "Finandina";
  } else {
    return "Sin información de bin";
  }
}